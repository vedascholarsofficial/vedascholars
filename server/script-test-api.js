async function run() {
    try {
        const token = jwt.sign({ id: '65e31a9b2d8f991f8c1b1234', role: 'student' }, process.env.JWT_SECRET || 'fallbacksecret');
        const form = new FormData();
        form.append('resume', fs.createReadStream(testPDF));
        
        console.log("Sending...");
        const response = await axios.post('http://localhost:5000/api/user/resume/upload', form, {
            headers: {
                ...form.getHeaders(),
                Authorization: `Bearer ${token}`
            }
        });
        console.log("SUCCESS:", response.data);
    } catch (e) {
        console.error("ERROR:");
        console.error(e.response ? e.response.data : e.message);
    }
}
